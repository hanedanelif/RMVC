"""# **Tekstil veri seti için en yoğun matrisi bulma:**"""

import pandas as pd

# 1. Veri setini yüklüyoruz
# Dosya yolunun Colab'deki dosya yoluyla aynı olduğundan emin ol
df = pd.read_csv('FirmaUrunMin9_Miktar_AlimSayisi.csv')

# 2. Veriyi kontrol etmek için ilk birkaç satıra bakalım (İsteğe bağlı, görmek için)
print("Ham Veri:")
print(df.head())

# 3. Firma x Ürün Matrisini Oluşturma (Pivot Table Yöntemi)
# index: Satırlar (FirmaID)
# columns: Sütunlar (UrunTID)
# values: Hücre içindeki değerler (Miktar)
# fill_value=0: Eğer veri yoksa (NaN) yerine 0 koyar.
firma_urun_matrisi = df.pivot_table(index='FirmaID',
                                    columns='UrunTID',
                                    values='Miktar',
                                    aggfunc='sum',
                                    fill_value=0)

# 4. Oluşan matrisin boyutunu ve ilk 5 satırını görelim
print("\nMatris Boyutu (Satır, Sütun):", firma_urun_matrisi.shape)
print("\nFirma x Ürün Matrisinin İlk 5 Satırı:")
print(firma_urun_matrisi.head())

# İstersen bu matrisi daha sonra kullanmak üzere kaydedebilirsin
firma_urun_matrisi.to_csv('Firma_Urun_Matrisi.csv')

