"""**Adım 3:** Delta Fonksiyonunun Oluşturulması
Bu fonksiyon, algoritmanın kalbidir. Bir firmanın almadığı bir ürünün, o firmanın aldığı diğer ürünlerle olan ilişkisini (birlikte görülme sıklığını) hesaplar.

Açıklama:

Fonksiyon, belirli bir firma (hedef_firma_id) için henüz almadığı ürünleri (alinmayan_urunler) belirler.

Sonra bu aday ürünlerin her birini, firmanın mevcut ürünleriyle tek tek eşleştirir.

{aday_urun, mevcut_urun}.issubset(diger_firma_urunleri): Bu satır, "Acaba bu aday ürün ile mevcut ürün, başka herhangi bir firmanın sepetinde birlikte var mı?" diye kontrol eder. Eğer varsa, toplam_skor artar. Bu, "Bu ürünü alanlar, şunu da aldı" mantığının matematiksel karşılığıdır.
"""

# 3. Delta Fonksiyonu (İlişki Sıklığı Hesaplama)

def delta_function(hedef_firma_id, tum_firmalar_dict, tum_urunler_seti):
    """
    Bir firmanın almadığı ürünler için 'birliktelik skoru' hesaplar.
    """
    # Hedef firmanın aldığı ürünler
    hedef_firmanin_urunleri = tum_firmalar_dict[hedef_firma_id]

    # Hedef firmanın ALMADIĞI ürünler (Tüm ürünler - Aldıkları)
    alinmayan_urunler = tum_urunler_seti - hedef_firmanin_urunleri

    sonuclar = {}

    # Alınmayan her bir ürün için döngü
    for aday_urun in alinmayan_urunler:
        toplam_skor = 0

        # Firmanın halihazırda aldığı her bir ürün ile karşılaştır
        for mevcut_urun in hedef_firmanin_urunleri:
            # Bu ikili (aday_urun ve mevcut_urun) başka hangi firmalarda BERABER bulunuyor?
            for diger_firma_urunleri in tum_firmalar_dict.values():
                # Eğer her iki ürün de o firmada varsa skoru artır
                if {aday_urun, mevcut_urun}.issubset(diger_firma_urunleri):
                    toplam_skor += 1
                    # Bir firmada bir kere bulmak yeterli (Binary mantığı), break ile o firmayı geçebiliriz
                    # Ancak makaledeki mantık toplam frekansa bakıyor olabilir, burada counter mantığı işliyor.
                    # Kodunuzdaki "continue" sadece iç döngüyü (diğer elementleri) atlamaz, for döngüsünün akışını etkiler.
                    # Burada basitçe: "Bu ikili kaç firmada beraber görülmüş?" sorusunu soruyoruz.

        sonuclar[aday_urun] = toplam_skor

    return sonuclar

"""**Adım 4:** Üyelik Matrisinin (Membership Matrix) Oluşturulması
Delta fonksiyonundan gelen skorları normalize ederek 0 ile 1 arasında bir "üyelik derecesi"ne (olasılık gibi düşünebilirsin) dönüştürürüz.

**Açıklama:**

Her firma için delta_function çalıştırılır ve ham skorlar alınır.

g_coeff: Skorları normalize etmek için kullanılır. Bir ürünün alabileceği maksimum puanı temsil eder.

Eğer ürün zaten firmanın sepetindeyse değeri 1.0 olarak sabitlenir.

Eğer ürün sepette yoksa ama diğer ürünlerle ilişkisi varsa, hesaplanan skor 0 ile 1 arasında bir değere (olasılığa) dönüşür
"""

# 4. Üyelik Matrisini Oluşturma

def create_membership_matrix(firma_idleri, tum_firmalar_dict, tum_urunler_seti):
    uyelik_matrisi = {firma_id: {} for firma_id in firma_idleri}

    for firma_id in firma_idleri:
        # Delta fonksiyonunu çalıştır
        delta_sonuclari = delta_function(firma_id, tum_firmalar_dict, tum_urunler_seti)

        # Normalizasyon katsayısı (g_coeff)
        # Firmanın aldığı ürün sayısı * (Toplam firma sayısı - 1)
        # Bu, olası maksimum birliktelik sayısıdır.
        g_coeff = len(tum_firmalar_dict[firma_id]) * (len(tum_firmalar_dict) - 1)

        if g_coeff == 0: g_coeff = 1 # Sıfıra bölünme hatasını önle

        for urun in tum_urunler_seti:
            if urun in delta_sonuclari:
                # Alınmayan ürünse: Skor / Katsayı (0-1 arası değer)
                val = delta_sonuclari[urun] / g_coeff
            elif urun in tum_firmalar_dict[firma_id]:
                # Zaten alınmış ürünse: Değer 1.0
                val = 1.0
            else:
                # Hiçbir ilişki yoksa: 0.0
                val = 0.0

            uyelik_matrisi[firma_id][urun] = val

    return uyelik_matrisi

print("\n⏳ RMVC Matrisi Hesaplanıyor... (Bu işlem biraz zaman alabilir)")
mem_matrix = create_membership_matrix(E_named.keys(), E_named, U)
