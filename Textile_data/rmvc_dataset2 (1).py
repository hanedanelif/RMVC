def calculate_density(matrix):
    total_elements = matrix.size # Toplam kutucuk sayısı
    non_zero_elements = np.count_nonzero(matrix) # 0 olmayan (işlem gören) kutucuk sayısı
    density = (non_zero_elements / total_elements) * 100 # Yüzde hesabı
    return density

