def print_soft_set_definition(U, E_named):
    sorted_u = sorted(list(U), key=lambda x: int(x))
    sorted_e = sorted(E_named.keys(), key=lambda x: int(x.split('_')[1]))

    print("\n" + "="*100)
    print(f"{'SOFT SET DEFINITION (MATEMATİKSEL TANIM)':^100}")
    print("="*100)

    u_str = ", ".join(sorted_u)
    print(f"U (Universal Set) = {{{u_str}}}")
    print("-" * 100)

    e_str = ", ".join(sorted_e)
    print(f"E (Parameters)    = {{{e_str}}}")
    print("-" * 100)

    print("Mappings (Φ):")
    for e_key in sorted_e:
        elements = sorted(list(E_named[e_key]), key=lambda x: int(x))
        elements_str = ", ".join(elements) if elements else "∅"
        print(f"  Φ({e_key}) = {{{elements_str}}}")
    print("="*100)
    print("\n")

