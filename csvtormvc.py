def load_and_map_csv_content(csv_content):
    """
    CSV içeriğini (string) okur, Ürünleri (1,2,3..) ve Firmaları (e_1,e_2..) olarak kodlar.
    """
    try:
        E_named = {}          # { 'e_1': {'1', '3'}, ... }
        firm_mapping = {}     # { 'e_1': 'GerçekFirmaID' }
        product_mapping = {}  # { '1': 'GerçekÜrünID' }
        U = set()             # Evrensel küme (1, 2, 3...)

        # Dosya içeriğini satırlara böl
        lines = csv_content.splitlines()

        # --- 1. Başlık Satırı (Ürün İsimlerini Kodla) ---
        header_line = lines[0].strip()
        headers = header_line.split(',')

        real_product_ids = [pid.strip() for pid in headers[1:]] # İlk sütun hariç

        # Ürünleri 1'den başlayarak numaralandır
        real_to_simple_prod = {}
        for idx, real_pid in enumerate(real_product_ids):
            simple_id = str(idx + 1) # "1", "2", "3"...
            product_mapping[simple_id] = real_pid
            real_to_simple_prod[real_pid] = simple_id

        U = set(product_mapping.keys())

        # --- 2. Veri Satırlarını İşle (Firmaları Kodla) ---
        valid_rows = 0
        for index, line in enumerate(lines[1:]):
            line = line.strip()
            if not line: continue

            parts = line.split(',')
            real_firma_id = parts[0].strip()
            quantities = parts[1:]

            bought_products_simple = set()

            # Miktarları kontrol et
            for i, qty in enumerate(quantities):
                try:
                    if i < len(real_product_ids) and float(qty) > 0:
                        real_pid = real_product_ids[i]
                        simple_pid = real_to_simple_prod[real_pid]
                        bought_products_simple.add(simple_pid)
                except ValueError:
                    continue

            # Firma kod adı atama (e_1, e_2...)
            code_name = f"e_{valid_rows+1}"

            E_named[code_name] = bought_products_simple
            firm_mapping[code_name] = real_firma_id
            valid_rows += 1

        print(f"\n[BİLGİ] Veri yüklendi. {len(U)} ürün ve {len(E_named)} firma işlendi.")
        return U, E_named, firm_mapping, product_mapping

    except Exception as e:
        print(f"[HATA] Veri işlenirken sorun oluştu: {e}")
        return None, None, None, None

