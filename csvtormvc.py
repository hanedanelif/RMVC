def print_binary_matrix(E_named, prod_map):
    sorted_product_keys = sorted(prod_map.keys(), key=lambda x: int(x))
    sorted_firms = sorted(E_named.keys(), key=lambda x: int(x.split('_')[1]))
    col_width = 8

    print("="*100)
    print(f"{'INITIAL BINARY MATRIX (1=Var, 0=Yok)':^100}")
    print("="*100)

    header_str = f"{'SETS':<12}"
    for pid in sorted_product_keys:
        header_str += f"{pid:>{col_width}}"
    print(header_str)
    print("-" * len(header_str))

    for e_key in sorted_firms:
        row_str = f"{e_key:<12}"
        current_set = E_named[e_key]
        for pid in sorted_product_keys:
            val = "1" if pid in current_set else "0"
            row_str += f"{val:>{col_width}}"
        print(row_str)

    print("-" * len(header_str))
    print("\n")

