# 4. RMVC HESAPLAMA MOTORU
# ==========================================

def delta_function(e_name, E_named, U):
    e_set = E_named[e_name]
    not_in_e_set = U - e_set
    results = {}
    all_sets_list = list(E_named.values())

    for element in not_in_e_set:
        total_sum = 0
        for other_element in e_set:
            pair = {element, other_element}
            count = sum(1 for s in all_sets_list if pair.issubset(s))
            total_sum += count
        results[element] = total_sum
    return results

def create_membership_matrix(E_keys, E_named, U):
    membership_matrix = {e_key: {} for e_key in E_keys}
    total_sets = len(E_named)

    print("[İŞLEM] RMVC Matrisi hesaplanıyor, lütfen bekleyin...")

    for e_key in E_keys:
        delta_results = delta_function(e_key, E_named, U)
        current_set_len = len(E_named[e_key])
        g_coeff = current_set_len * (total_sets - 1) if total_sets > 1 else 1

        for element in U:
            if element in delta_results:
                val = Fraction(delta_results[element], g_coeff) if g_coeff != 0 else 0
            else:
                val = 1
            membership_matrix[e_key][element] = val

    return membership_matrix

