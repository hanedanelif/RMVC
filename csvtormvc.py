def print_full_report(matrix, firm_map, prod_map):
    sorted_product_keys = sorted(prod_map.keys(), key=lambda x: int(x))
    sorted_firms = sorted(matrix.keys(), key=lambda x: int(x.split('_')[1]))
    col_width = 10

    print("="*110)
    print(f"{'MEMBERSHIP VALUE MATRIX (BAĞIL ÜYELİK MATRİSİ)':^110}")
    print("="*110)

    header_str = f"{'SETS':<12}"
    for pid in sorted_product_keys:
        header_str += f"{pid:>{col_width}}"
    print(header_str)
    print("-" * len(header_str))

    column_sums = {pid: 0.0 for pid in sorted_product_keys}

    for e_key in sorted_firms:
        row_str = f"{e_key:<12}"
        for pid in sorted_product_keys:
            val = float(matrix[e_key][pid])
            column_sums[pid] += val
            row_str += f"{val:>{col_width}.4f}"
        print(row_str)

    print("-" * len(header_str))

    sum_str = f"{'SUM s(x)':<12}"
    for pid in sorted_product_keys:
        sum_str += f"{column_sums[pid]:>{col_width}.4f}"
    print(sum_str)
    print("="*110)
    print("\n")

    # KARAR AŞAMASI
    print("="*75)
    print(f"{'DECISION MAKING PHASE (KARAR AŞAMASI)':^75}")
    print("="*75)

    sorted_scores = sorted(column_sums.items(), key=lambda x: x[1], reverse=True)

    print(f"{'Rank':<6} | {'Prod ID':<10} | {'Score s(x)':<15} | {'Original Product ID'}")
    print("-" * 75)

    for rank, (pid, score) in enumerate(sorted_scores, 1):
        prefix = "★ " if rank == 1 else "  "
        real_name = prod_map[pid]
        print(f"{prefix}{rank:<4} | {pid:<10} | {score:<15.4f} | {real_name}")

    print("-" * 75)
    winner_simple = sorted_scores[0][0]
    winner_real = prod_map[winner_simple]
    winner_score = sorted_scores[0][1]
    print(f"\n>>> FINAL DECISION: Optimal Product is '{winner_simple}' (Orig: {winner_real})")
    print(f">>> Highest Score: {winner_score:.4f}")
    print("="*75)
    print("\n")

    # REFERANS TABLOLARI
    print("#" * 30)
    print(f"{'REFERENCE TABLES':^30}")
    print("#" * 30)

    print("\n--- [1] FIRM ID MAPPING ---")
    print(f"{'Code':<10} | {'Original Firm ID'}")
    print("-" * 35)
    for code in sorted_firms:
        print(f"{code:<10} | {firm_map[code]}")

    print("\n--- [2] PRODUCT ID MAPPING ---")
    print(f"{'New ID':<10} | {'Original Product ID'}")
    print("-" * 35)
    for pid in sorted_product_keys:
        print(f"{pid:<10} | {prod_map[pid]}")

